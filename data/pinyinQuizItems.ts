export type PinyinQuizMode = "character" | "word";

export interface PinyinQuizItem {
  id: string;
  mode: PinyinQuizMode;
  text: string;
  pinyin: string;
  /** Word the character is taken from, shown after answering; the word itself for word questions. */
  word: string;
  meaning?: string;
}

