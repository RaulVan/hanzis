import { expect, test } from "@playwright/test";
import { AxeBuilder } from "@axe-core/playwright";

for (const width of [1440, 375]) for (const source of ["curated", "imported"]) test(`inline dictionary keeps ${source} poetry state at ${width}px`, async ({ page }) => {
  const imported = source === "imported";
  const route = imported ? "/poetry/read/?poem=haitang-10095" : "/poetry/jing-ye-si/";
  const char = imported ? "岱" : "床";
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  const requests: string[] = [];
  page.on("request", request => requests.push(request.url()));
  await page.setViewportSize({ width, height: width === 375 ? 812 : 1000 });
  await page.goto(route);
  const character = page.locator(`.poem-verses a[data-poetry-character="${char}"]`).first();
  await expect(character).toBeVisible();
  expect(requests.filter(url => /\/dictionary\/.*\.json/.test(url))).toEqual([]);
  const toggle = page.getByRole("switch", { name: "显示拼音" });
  if (!await toggle.isChecked()) await toggle.click();
  await expect(character.locator("rt")).toBeVisible();
  await character.scrollIntoViewIfNeeded();
  const scroll = await page.evaluate(() => scrollY);
  await character.click();
  const dialog = page.getByRole("dialog", { name: `“${char}”的字典` });
  await expect(dialog.getByRole("article", { name: `${char}的释义` })).toBeVisible();
  await expect(dialog.getByText("部首", { exact: true })).toBeVisible();
  await expect(dialog.getByText("笔画", { exact: true })).toBeVisible();
  await dialog.getByText("部首", { exact: true }).click();
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole("heading", { name: "词典释义", exact: true })).toBeVisible();
  await expect(dialog).toContainText("國語辭典簡編本");
  await expect(page).toHaveURL(route);
  const box = await dialog.boundingBox();
  expect(box!.width).toBeLessThanOrEqual(width - 30);
  expect(box!.height).toBeLessThanOrEqual((width === 375 ? 812 : 1000) * 0.8 + 1);
  expect(box!.y).toBeGreaterThanOrEqual(0);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: `/tmp/hanzis-poem-dictionary-${source}-${width}.png` });
  await dialog.getByRole("button", { name: "继续读诗" }).click();
  await expect(dialog).toHaveCount(0);
  await expect(character).toBeFocused();
  expect(Math.abs(await page.evaluate(() => scrollY) - scroll)).toBeLessThanOrEqual(2);
  await expect(toggle).toBeChecked();
  await page.keyboard.press("Enter");
  await expect(dialog).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(character).toBeFocused();
  await toggle.click();
  await character.click();
  await expect(dialog).toBeVisible();
  await page.mouse.click(8, 8);
  await expect(dialog).toHaveCount(0);
  await expect(character).toBeFocused();
  await expect(page).toHaveURL(route);
  await character.click();
  await dialog.getByRole("button", { name: "关闭", exact: true }).click();
  await character.click();
  await dialog.getByRole("link", { name: "显示详细" }).click();
  await expect(page).toHaveURL(`/dictionary/?q=${encodeURIComponent(char)}`);
  await expect(page.getByRole("article", { name: `${char}的释义` })).toBeVisible();
  expect(errors).toEqual([]);
});

const shardPattern = /\/dictionary\/(?:moe\/|revised\/|xinhua\/)?[0-9a-f]{2}\.json$/;
test("dictionary dialog distinguishes complete failure, partial failure and absent definitions", async ({ page }) => {
  await page.route(shardPattern, route => route.abort());
  await page.goto("/poetry/?poem=haitang-10095");
  const character = page.locator('.poem-verses a[data-poetry-character="岱"]').first();
  await character.click();
  const dialog = page.getByRole("dialog", { name: "“岱”的字典" });
  await expect(dialog.getByText("释义数据暂时无法读取", { exact: false })).toBeVisible();
  await expect(dialog.getByText("当前词库还没有", { exact: false })).toHaveCount(0);
  await page.unroute(shardPattern);
  await page.route("**/dictionary/moe/*.json", route => route.abort());
  await dialog.getByRole("button", { name: "重新加载", exact: true }).click();
  await expect(dialog).toContainText("简编本暂时无法读取");
  await expect(dialog.getByRole("region", { name: "修订本释义" })).toBeVisible();
  await page.unroute("**/dictionary/moe/*.json");
  await dialog.getByRole("button", { name: "重试缺失释义" }).click();
  await expect(dialog.getByRole("heading", { name: "词典释义", exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "重试缺失释义" })).toHaveCount(0);
  await page.route(shardPattern, route => route.fulfill({ json: {} }));
  await page.reload();
  await character.click();
  await expect(dialog.getByText("当前词库还没有这个字的释义。")).toBeVisible();
  await expect(dialog.getByRole("link", { name: "显示详细" })).toBeVisible();
});

test("a late dictionary response cannot reopen a closed dialog or replace another character", async ({ page }) => {
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route(shardPattern, async route => {
    if (route.request().url().endsWith("31.json")) await gate;
    await route.continue();
  });
  await page.goto("/poetry/read/?poem=haitang-10095");
  await page.locator('.poem-verses a[data-poetry-character="岱"]').click();
  const first = page.getByRole("dialog", { name: "“岱”的字典" });
  await expect(first.getByRole("status", { name: "正在加载释义" })).toBeVisible();
  await first.getByRole("button", { name: "关闭", exact: true }).click();
  await page.locator('.poem-verses a[data-poetry-character="宗"]').click();
  const second = page.getByRole("dialog", { name: "“宗”的字典" });
  await expect(second.getByRole("article", { name: "宗的释义" })).toBeVisible();
  const lateResponse = page.waitForResponse(response => /\/dictionary\/(?:moe\/|revised\/|xinhua\/)?31\.json$/.test(response.url()));
  release();
  await lateResponse;
  await expect(first).toHaveCount(0);
  await expect(second.getByRole("article", { name: "宗的释义" })).toBeVisible();
  await second.getByRole("button", { name: "继续读诗" }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
});
